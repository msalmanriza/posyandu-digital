export function getKmsZone(beratKg, umurBln, sex) {
  if (beratKg == null || umurBln == null) return null;
  const ref = lookupRef(sex === "P" ? WHO_FEMALE : WHO_MALE, umurBln);
  if (beratKg < ref.m2) return { key: "bgm", ...KMS_ZONES.bgm };
  if (beratKg < ref.m1) return { key: "kuningBawah", ...KMS_ZONES.kuningBawah };
  if (beratKg < ref.med) return { key: "hijauMuda", ...KMS_ZONES.hijauMuda };
  if (beratKg < ref.p1) return { key: "hijauTua", ...KMS_ZONES.hijauTua };
  if (beratKg < ref.p2) return { key: "kuningAtas", ...KMS_ZONES.kuningAtas };
  return { key: "merahAtas", ...KMS_ZONES.merahAtas };
}