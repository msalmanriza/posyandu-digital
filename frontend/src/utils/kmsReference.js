export function lookupRef(ref, m) {
  const mono = Math.min(60, Math.max(0, m));
  if (mono <= 0) return ref[0];
  if (mono >= 60) return ref[ref.length - 1];
  let lo = ref[0];
  let hi = ref[ref.length - 1];
  for (let i = 0; i < ref.length - 1; i++) {
    if (mono >= ref[i].m && mono <= ref[i + 1].m) {
      lo = ref[i];
      hi = ref[i + 1];
      break;
    }
  }
  const t = (mono - lo.m) / (hi.m - lo.m || 1);
  const lerp = (a, b) => a + t * (b - a);
  return {
    m3: lerp(lo.m3, hi.m3),
    m2: lerp(lo.m2, hi.m2),
    m1: lerp(lo.m1, hi.m1),
    med: lerp(lo.med, hi.med),
    p1: lerp(lo.p1, hi.p1),
    p2: lerp(lo.p2, hi.p2),
    p3: lerp(lo.p3, hi.p3),
  };
}

